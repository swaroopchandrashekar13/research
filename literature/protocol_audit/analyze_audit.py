"""Protocol-audit analysis (PROTOCOL.md 'Output'): shares with Wilson 95% CIs and the candidate-artefact table.

Usage: python -I literature/protocol_audit/analyze_audit.py   (writes literature/protocol_audit/RESULTS.md)
"""
from __future__ import annotations

import csv
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Exposure rules for the text-amount confound (CODING_CONVENTIONS.md), applied to each included paper:
#   exposed           count-based comparison (fixed_k, or a count-based rank metric without cutoff) of arms whose
#                     chunk lengths differ, with retrieved text neither matched nor reported
#   possibly exposed  count-based comparison, arm lengths unclear
#   not exposed       budget-matched, or count-based with lengths matched by design, or the retrieved unit does not
#                     depend on the chunker (page/document ranking)
#   undeterminable    selection protocol not stated
# Two 'other' protocols need a judgement, recorded here rather than hidden in code:
COUNT_BASED_OTHER = {"garrido2026chunksize"}  # reciprocal rank over chunks: positions counted in chunks
UNIT_INDEPENDENT = {"pdfparsingfin2026", "reconstructingcontext2025", "gunther2024latechunking"}  # pages/documents


def wilson(k: int, n: int, z: float = 1.959963984540054) -> tuple[float, float]:
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre - half, centre + half


def exposure(r: dict) -> str:
    proto, length = r["selection_protocol"], r["chunk_length_differs_between_arms"]
    if proto == "unclear":
        return "undeterminable"
    if proto == "fixed_budget" or r["key"] in UNIT_INDEPENDENT:
        return "not exposed"
    count_based = proto == "fixed_k" or r["key"] in COUNT_BASED_OTHER
    if not count_based:
        return "undeterminable"
    if length == "no":
        return "not exposed"
    if r["reports_retrieved_text_amount"] == "yes":
        return "exposed, text reported"
    return "exposed" if length == "yes" else "possibly exposed"


def main() -> None:
    with open(HERE / "coding.csv", newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["included"] == "yes"]
    n = len(rows)
    for r in rows:
        r["exposure"] = exposure(r)

    def share(label, pred):
        k = sum(1 for r in rows if pred(r))
        lo, hi = wilson(k, n)
        return f"| {label} | {k}/{n} | {100 * k / n:.0f}% | [{100 * lo:.0f}, {100 * hi:.0f}] |"

    multi = lambda r: r["n_datasets"].split()[0].isdigit() and int(r["n_datasets"].split()[0]) > 1  # noqa: E731
    lines = [
        "# Protocol audit — results",
        "",
        f"*Generated by `analyze_audit.py` from `coding.csv` ({n} included papers). Coder: AI (mentor); the researcher's "
        "blind double-coding (`reliability_order.txt`) and Cohen's κ are still pending, so these shares are "
        "**provisional**.*",
        "",
        "## Planned shares (Wilson 95% CIs)",
        "",
        "| Quantity | k/n | Share | 95% CI (%) |",
        "|---|---:|---:|---|",
        share("(a) compares at a fixed number of retrieved chunks (`fixed_k`)", lambda r: r["selection_protocol"] == "fixed_k"),
        share("(a') budget-matched (`fixed_budget` or `both`)", lambda r: r["selection_protocol"] in ("fixed_budget", "both")),
        share("(b) reports the amount of retrieved text", lambda r: r["reports_retrieved_text_amount"] == "yes"),
        share("(b') controls text amount (budget, matched lengths, or chunker-independent unit)",
              lambda r: r["exposure"] == "not exposed"),
        share("(c) reports uncertainty for chunking contrasts (CI or test)",
              lambda r: r["uncertainty_reported"] in ("CI", "significance_test")),
        share("(d) evaluates on more than one dataset", multi),
        share("(e) headline claim exposed to the text-amount confound (exposed, with or without text reported)",
              lambda r: r["exposure"].startswith("exposed")),
        "",
        "## Exposure to the text-amount confound (rules in `analyze_audit.py`)",
        "",
        "| Exposure | Papers |",
        "|---|---|",
    ]
    for level in ("exposed", "exposed, text reported", "possibly exposed", "not exposed", "undeterminable"):
        keys = [r["key"] for r in rows if r["exposure"] == level]
        lo, hi = wilson(len(keys), n)
        lines.append(f"| {level} ({len(keys)}/{n}; CI [{100 * lo:.0f}, {100 * hi:.0f}]%) | {', '.join(keys) or '—'} |")
    lines += [
        "",
        "## Candidate artefacts: headline claims comparing arms of different chunk length at a fixed number of chunks",
        "",
        "We do **not** claim these conclusions are wrong; only that the protocol leaves the text-amount confound "
        "uncontrolled for the quoted claim (PROTOCOL.md 'Output').",
        "",
        "| Paper | k | Headline claim | Note |",
        "|---|---|---|---|",
    ]
    for r in rows:
        if r["exposure"] in ("exposed", "exposed, text reported"):
            lines.append(f"| `{r['key']}` | {r['k_values']} | {r['headline_claim']} | {r['notes']} |")
    (HERE / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:30]))


if __name__ == "__main__":
    main()
