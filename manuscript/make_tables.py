def reps_tex(e2: dict) -> str:
    reps = (e2.get("analysis_settings") or {}).get("bootstrap_resamples", 2000)  # 2,000 = the logged analysis setting
    return f"{reps:,}".replace(",", "{,}")


def e2_tables(e2: dict) -> None:
    meas = (("f1", "Answer F1"), ("em", "Exact match"), ("coverage", "Coverage"))
    rows, rules = [], set()
    for cid in ("P1", "S3-256"):
        if rows:
            rules.add(len(rows))
        for d in DS + ("pooled",):
            src = e2["pooled"][cid] if d == "pooled" else e2["datasets"][d]["claims"][cid]
            cells = []
            for m, _ in meas:
                r = src[m] if d == "pooled" else src[m]["did"]
                est = r["did"] if d == "pooled" else r["mean"]
                cells.append(f"{signed(est)} {ci(r['lo'], r['hi'], 1, '+.3f')}")
            name = "Pooled (stratified)" if d == "pooled" else DS_NAME[d]
            rows.append([cid if d == DS[0] else "", name] + cells)
        p = e2["pooled"][cid]
        rows.append(["", "Minimum detectable effect"] + [f"{p[m]['mde']:.3f}" for m, _ in meas])
    write("e2_did", "Answer-quality check (exploratory; analysis plan in experiments/E2\\_generation/ANALYSIS\\_PLAN.md): "
          "difference-in-differences DiD $= \\Delta(B{=}1{,}024) - \\Delta(k{=}5)$, $\\Delta$ = metric(A) $-$ "
          f"metric(B), with 95\\% bootstrap CIs ({reps_tex(e2)} resamples; pooled: stratified by dataset). The retrieval "
          "mechanism predicts DiD $> 0$; an interval that includes 0 does not establish the absence of an effect. "
          "50 queries per dataset; reader Qwen3-4B (Q4\\_K\\_M, greedy).", "tab:e2did",
          "@{}llrrr@{}", ["Claim", "Dataset"] + [n for _, n in meas], rows, size="\\footnotesize", star=True,
          midrules=rules)
    rows = []
    for d in DS:
        x = e2["datasets"][d]
        g = x["diagnostics"]
        trunc = g["finish_reasons"].get("length", 0)
        link = x["retrieval_answer_link"]
        rows.append([DS_NAME[d], f"{g['jobs_ok']}/{g['rows_total']}", f"{trunc}", pct(g["unanswerable_rate"]),
                     f"{link['pearson_coverage_f1']:.2f}", f"{link['mean_f1_hit_lenient_1']:.2f}",
                     f"{link['mean_f1_hit_lenient_0']:.2f}"])
    write("e2_diagnostics", "Answer-quality check, planned diagnostics per dataset (400 generations each): "
          "completed jobs, answers truncated at the 256-token cap, share of ``unanswerable'' replies, and the link "
          "between retrieval and answers (Pearson correlation of coverage and F1; mean F1 when the gold evidence was "
          "/ was not at least half retrieved).", "tab:e2diag", "@{}lrrrrrr@{}",
          ["Dataset", "Jobs ok", "Truncated", "Unanswerable (\\%)", "$r$(coverage, F1)", "F1 | hit", "F1 | miss"],
          rows, size="\\footnotesize")


def audit_table() -> None:
    sys.path.insert(0, str(AUDIT.parent))
    from analyze_audit import exposure  # the audit's own rules

    proto = {"fixed_k": "fixed $k$", "fixed_budget": "budget", "both": "both", "other": "other", "unclear": "unclear"}
    unc = {"none": "none", "seeds_only": "seeds", "CI": "CI", "significance_test": "test"}
    rows = []
    for r in csv.DictReader(open(AUDIT)):
        if r["included"] != "yes":
            continue
        rows.append([f"\\citeL{{{r['key']}}}", proto.get(r["selection_protocol"], r["selection_protocol"]),
                     r["chunk_length_differs_between_arms"], r["reports_retrieved_text_amount"],
                     unc.get(r["uncertainty_reported"], r["uncertainty_reported"]), r["metric_type"], exposure(r)])
    write("audit", "Protocol audit: coding of each included study (provisional; see Section~\\ref{sec:audit}). "
          "Protocol: how arms are compared; Length differs: whether the compared arms produce chunks of different "
          "length; Text reported: whether the amount of retrieved text is reported; Uncertainty: for chunking "
          "contrasts; Exposure: derived by the coding rules in \\texttt{analyze\\_audit.py}.", "tab:audit",
          "@{}lllllll@{}", ["Study", "Protocol", "Length differs", "Text reported", "Uncertainty", "Metric", "Exposure"],
          rows, size="\\footnotesize", star=True)


def posthoc_table(e1: dict, ph1: Path, ph3: Path) -> None:
    """POST-HOC character-metric sensitivity: stored word results vs re-executed selections rescored."""
    flips = json.loads((ph1 / "summary.json").read_text())["universe_verdict_changes_vs_stored"]
    variants = [("Stored (words, float16)", e1, None)] + [
        (label, json.loads((ph1 / v / "results.json").read_text()), v)
        for v, label in (("word64", "Words, float64"), ("char", "Characters"), ("char_nows", "Non-space characters"))]
    rows = []
    for label, r, v in variants:
        rows.append([label, f"{pct(r['H1']['estimate'])} {ci(*r['H1']['ci95'])}", f"{pct(r['H1b']['estimate'])} "
                     f"{ci(*r['H1b']['ci95'])}", f"{r['H2']['eta2']['dataset']:.3f}",
                     pct(r["H3"]["share_universes_requiring_over_500"]),
                     "---" if v is None else f"{flips[v]['changed']:,}"])
    e3 = json.loads((ph3 / "summary.json").read_text())
    names = {"stored (word, float16)": "Stored (words, float16)", "word64": "Words, float64", "char": "Characters",
             "char_nows": "Non-space characters"}
    rows3 = [[f"Study 1b BM25: {names[k]}", f"{pct(q['H4_bm25']['estimate'])} {ci(*q['H4_bm25']['ci95'])}",
              f"{pct(q['H4b_bm25']['estimate'])} {ci(*q['H4b_bm25']['ci95'])}", "", "", ""] for k, q in e3.items()]
    write("posthoc_charmetric", "Post-hoc sensitivity (not in the analysis plans): hypothesis estimates (pp, 95\\% CI) when the "
          "re-executed BM25 selections, which reproduce every stored score and word count, are scored on words (as reported), on words without float16 storage, "
          "on characters, and on non-whitespace characters. Study 1 columns: H1, H1b, H2 dataset $\\eta^2$, H3 share "
          "of universes needing $n>500$, and universe verdicts that change relative to the stored scores (of 24{,}960). "
          "Study 1b rows give the H4 and H4b forms restricted to BM25 universes (the dense arm was not re-executed).",
          "tab:charmetric", "@{}lrrrrr@{}", ["Scoring", "H1 / H4 (BM25)", "H1b / H4b (BM25)", "$\\eta^2$ dataset",
                                             "H3 $n>500$ (\\%)", "Changed verdicts"],
          rows + rows3, size="\\footnotesize", midrules={len(rows)})


FIGURES = ("verdict_dumbbell", "speccurve_P1_coverage", "speccurve_S3-256_coverage", "study1b_dumbbell")


def figures(src_dir: Path, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    for stem in FIGURES:
        for ext in ("pdf", "coords.json"):
            shutil.copy(src_dir / f"{stem}.{ext}", dest / f"{stem}.{ext}")


def main(argv=None) -> None:
    global E1, E1RUN, E2, E3, E3RUN, AUDIT, OUT, FIG
    ap = argparse.ArgumentParser()
    ap.add_argument("--e1", type=Path, default=E1)
    ap.add_argument("--e1-run", type=Path, default=E1RUN)
    ap.add_argument("--e2", type=Path, default=E2)
    ap.add_argument("--e3", type=Path, default=E3)
    ap.add_argument("--e3-run", type=Path, default=E3RUN)
    ap.add_argument("--audit", type=Path, default=AUDIT)
    ap.add_argument("--out-tables", type=Path, default=OUT)
    ap.add_argument("--posthoc-e1", type=Path, default=ROOT / "experiments/E1_retrieval_multiverse/analysis/posthoc-charmetric-20261024")
    ap.add_argument("--posthoc-e3", type=Path, default=ROOT / "experiments/E3_semantic_dense/analysis/posthoc-charmetric-bm25-20261024")
    ap.add_argument("--figures-from", type=Path)
    ap.add_argument("--out-figures", type=Path, default=FIG)
    args = ap.parse_args(argv)
    E1, E1RUN, E2, E3, E3RUN, AUDIT, OUT, FIG = (args.e1, args.e1_run, args.e2, args.e3, args.e3_run, args.audit,
                                                 args.out_tables, args.out_figures)
    OUT.mkdir(parents=True, exist_ok=True)
    e1 = json.loads((E1 / "results.json").read_text())
    e2 = json.loads((E2 / "results.json").read_text())
    e3 = json.loads((E3 / "results.json").read_text())
    m1, m3 = manifests(E1RUN), manifests(E3RUN)
    data_table(e1, m1)
    chunk_length_table(m1, m3)
    e1_claims_table(e1)
    e1_by_dataset_table(e1)
    e1_sensitivity_table(e1)
    e1_h2h3_table(e1)
    e3_tables(e3)
    e2_tables(e2)
    audit_table()
    posthoc_table(e1, args.posthoc_e1, args.posthoc_e3)
    if args.figures_from:
        figures(args.figures_from, FIG)
    print(f"{len(list(OUT.glob('*.tex')))} tables written to {OUT}")


if __name__ == "__main__":
    main()
