HEADER = "% Generated by manuscript/make_tables.py from logged results. Do not edit by hand.\n"


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def signed(x: float, fmt: str = "+.3f") -> str:
    return f"{x:{fmt}}".replace("-", "$-$")


def ci(lo: float, hi: float, scale: float = 100, fmt: str = ".1f") -> str:
    return f"[{signed(scale * lo, fmt)}, {signed(scale * hi, fmt)}]"


def tt(s: str) -> str:
    return "\\texttt{" + s.replace("_", "\\_") + "}"


def write(name: str, caption: str, label: str, colspec: str, head: list[str], rows: list[list[str]],
          note: str = "", size: str = "\\small", star: bool = False, midrules: set[int] = frozenset()) -> None:
    env = "table*" if star else "table"
    lines = [HEADER + f"\\begin{{{env}}}[t]\\centering{size}",
             f"\\caption{{{caption}}}\\label{{{label}}}",
             f"\\begin{{tabular}}{{{colspec}}}\\toprule"]
    lines += [" & ".join(h for h in head) + "\\\\\\midrule"] if head else []
    for i, r in enumerate(rows):
        if i in midrules:
            lines.append("\\midrule")
        lines.append(" & ".join(r) + "\\\\")
    lines.append("\\bottomrule\\end{tabular}")
    if note:
        lines.append("\\\\[3pt]\\parbox{\\linewidth}{\\footnotesize " + note + "}")
    lines.append(f"\\end{{{env}}}")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text("\n".join(lines) + "\n")


def manifests(run: Path) -> dict[str, dict]:
    return {d: json.loads((run / d / "manifest.json").read_text()) for d in DS}


def data_table(e1: dict, m1: dict) -> None:
    rows = []
    for d in DS:
        m = m1[d]
        rows.append([DS_NAME[d], DS_DOMAIN[d], f"{m['n_documents']:,}", f"{m['n_documents'] - m['n_documents_exploratory']:,}",
                     f"{e1['n_queries'][d]:,}"])
    rows.append(["Total", "", f"{sum(m1[d]['n_documents'] for d in DS):,}",
                 f"{sum(m1[d]['n_documents'] - m1[d]['n_documents_exploratory'] for d in DS):,}",
                 f"{sum(e1['n_queries'].values()):,}"])
    write("data", "Datasets. Documents are split 20/80 into exploratory and confirmatory sets (seed 20261018); queries "
          "follow their document. All results are on the confirmatory queries; the retrieval corpus is always the full "
          "dataset.", "tab:data", "@{}llrrr@{}",
          ["Dataset", "Domain", "Documents", "Confirmatory docs", "Confirmatory queries"], rows, midrules={4})


def chunk_length_table(m1: dict, m3: dict) -> None:
    order = [f"{f}-{w}" for f in ("fixed", "sentence", "paragraph") for w in (64, 128, 256, 512)]
    order[4:4] = [f"fixed-{w}-o25" for w in (64, 128, 256, 512)]
    stats1 = {d: {s["chunking"]: s for s in m1[d]["chunk_stats"]} for d in DS}
    stats3 = {d: {s["chunking"]: s for s in m3[d]["chunk_stats"]} for d in DS}
    rows = [[tt(c)] + [f"{stats1[d][c]['chunk_words_mean']:.0f}" for d in DS] for c in order]
    for c in ("semantic-bp", "semantic-cl"):
        rows.append([tt(c)] + [f"{stats3[d][c]['chunk_words_mean']:.0f}" for d in DS])
    rows.append(["\\quad non-contiguous chunks (\\%)"] + [pct(stats3[d]["semantic-cl"]["noncontiguous_share"]) for d in DS])
    write("chunk_lengths", "Mean chunk length in words per chunking and dataset (full retrieval corpus), from the run "
          "manifests; they depend only on the chunking, not on any retrieval metric. These lengths define the ``shorter arm'' of every "
          "Study~1b claim. The fixed chunkings of Study~1b are the same chunks as in Study~1.", "tab:chunklen",
          "@{}lrrrr@{}", ["Chunking"] + [DS_NAME[d] for d in DS], rows, midrules={16})


def e1_claims_table(e1: dict) -> None:
    rows, rules = [], set()
    prev = None
    for cid, v in e1["verdict_shares"].items():
        fam = cid.split("-")[0]
        if prev and fam != prev:
            rules.add(len(rows))
        prev = fam
        c, b = v["count"], v["budget"]
        rows.append([cid, v["role"], f"{tt(v['A'])} vs {tt(v['B'])}",
                     pct(c["support_A"]), pct(c["support_B"]), str(c["n_universes"]),
                     pct(b["support_A"]), pct(b["support_B"]), str(b["n_universes"])])
    write("e1_claims", "Study~1: share of universes (\\%) whose 95\\% paired-bootstrap CI supports arm A or arm B, per "
          "claim and selection protocol (confirmatory split); the remainder is inconclusive. Budget-matched universes "
          "use the admissible budgets $B \\ge$ the larger chunk size. $n$ = number of universes.", "tab:e1claims",
          "@{}lllrrrrrr@{}",
          ["Claim", "Role", "A vs B", "A (count)", "B (count)", "$n$", "A (budget)", "B (budget)", "$n$"],
          rows, size="\\footnotesize", star=True, midrules=rules)


def e1_by_dataset_table(e1: dict) -> None:
    rows, rules = [], set()
    for cid in ("P1", "S3-256"):
        v = e1["verdict_shares"][cid]
        if rows:
            rules.add(len(rows))
        for d in DS:
            c, b = v["count"]["by_dataset"][d], v["budget"]["by_dataset"][d]
            rows.append([cid if d == DS[0] else "", DS_NAME[d], pct(c["support_A"]), pct(c["support_B"]),
                         signed(c['mean_delta']), pct(b["support_A"]), pct(b["support_B"]), signed(b['mean_delta'])])
    write("e1_by_dataset", "Study~1 per dataset: share of universes (\\%) supporting arm A or B, and the mean "
          "difference $\\bar\\Delta = $ metric(A) $-$ metric(B) over universes. P1: A = fixed-128, B = fixed-512. "
          "S3-256: A = paragraph-256, B = fixed-256.", "tab:e1bydataset", "@{}llrrrrrr@{}",
          ["Claim", "Dataset", "A (count)", "B (count)", "$\\bar\\Delta$ (count)", "A (budget)", "B (budget)",
           "$\\bar\\Delta$ (budget)"], rows, size="\\footnotesize", midrules=rules)


def e1_sensitivity_table(e1: dict) -> None:
    names = {"a_bh_fdr": "(a) Benjamini--Hochberg FDR 5\\% within claim, protocol and dataset",
             "b_without_squad2": "(b) without SQuAD 2.0",
             "c_default_retriever": "(c) default retriever only (Lucene, $k_1$=1.5, $b$=0.75, stemmed)",
             "d_cluster_bootstrap": "(d) document-cluster bootstrap",
             "e_all_budgets": "(e) all budgets, including $B <$ chunk size"}
    h1 = e1["H1"]
    rows = [["Main analysis (as planned)", pct(h1["estimate"]), ci(*h1["ci95"])]]
    for k, label in names.items():
        r = e1["H1_sensitivity"][k]
        rows.append([label, pct(r["estimate"]), ci(*r["ci95"]) if "ci95" in r else "---"])
    write("e1_sensitivity", "Study~1, H1 under the planned sensitivity analyses: drop in the share of universes "
          "supporting fixed-512 from count- to budget-matched selection, in percentage points (threshold 20). (a) "
          "changes the verdict rule and has no joint-bootstrap CI.", "tab:e1sens", "@{}lrl@{}",
          ["Analysis", "Estimate (pp)", "95\\% CI"], rows, midrules={1})


def e1_h2h3_table(e1: dict) -> None:
    eta = e1["H2"]["eta2"]
    rows = [[f"$\\eta^2$ of {f}", f"{eta[f]:.3f}"] for f in ("dataset", "budget", "retriever", "metric")]
    rows.append(["dataset largest (share of bootstrap replicates)", pct(e1["H2"]["dataset_largest_fraction"]) + "\\%"])
    write("e1_h2", "Study~1, H2: main-effects decomposition of $\\Delta_u$ for S3-256 under budget-matched selection.",
          "tab:e1h2", "@{}lr@{}", ["Quantity", "Value"], rows)
    rows = [[cid, f"{v['median_required_n']:,.0f}", pct(v["share_over_500"])] for cid, v in e1["H3"]["by_claim"].items()]
    rows.append(["All S2 and S3 universes", f"{e1['H3']['median_required_n']:,.0f}",
                 pct(e1["H3"]["share_universes_requiring_over_500"])])
    write("e1_h3", "Study~1, H3: paired queries needed to detect $|\\delta| = 0.02$ ($\\alpha=0.05$ two-sided, power "
          "0.8), $n = ((1.96 + 0.8416)\\,\\sigma_d / 0.02)^2$, per budget-matched universe.", "tab:e1h3", "@{}lrr@{}",
          ["Claim", "Median $n$", "Universes with $n > 500$ (\\%)"], rows, midrules={len(rows) - 1})


