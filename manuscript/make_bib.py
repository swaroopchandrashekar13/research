"""Generate manuscript/refs.bib from literature/bibliography.yaml for every key cited in the manuscript .tex files.

Usage: .venv/bin/python -I manuscript/make_bib.py
Only verified entries (L1+) exist in bibliography.yaml, so nothing from memory can enter the paper. Entries below L3 get
a visible note; the reference draft also marks such citations with a red dagger (\\citeL).
"""
from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / "manuscript"


def cited_keys() -> list[str]:
    keys: list[str] = []
    for tex in sorted(HERE.glob("*.tex")) + sorted((HERE / "tables").glob("*.tex")):
        for group in re.findall(r"\\cite(?:L|p|t)?\{([^}#]*)\}", tex.read_text()):
            keys += [k.strip() for k in group.split(",") if k.strip() and k.strip() != "key"]
    return sorted(set(keys))


def authors(e: dict) -> str:
    names = e.get("authors") or []
    if not names:
        return "{[authors not yet verified]}"
    out = []
    for n in names:
        n = re.sub(r"\s*\(.*?\)", "", n).strip()
        if n.endswith("et al."):
            out += [n[: -len("et al.")].strip(), "others"]
        else:
            out.append(n)
    return " and ".join(out)


def esc(s: str) -> str:
    return s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")


def entry(e: dict) -> str:
    level = e["verification"]
    venue = str(e["venue"])
    fields = {"author": authors(e), "title": "{" + esc(e["title"]) + "}", "year": str(e["year"])}
    if venue.lower().startswith("arxiv"):
        kind = "misc"
        fields["howpublished"] = esc(f"{venue}, {e['id']}" if e.get("id") else venue)
    else:
        kind = "inproceedings" if any(w in venue for w in ("Findings", "ACL", "EMNLP", "NeurIPS", "CIKM", "SIGIR",
                                                          "NAACL")) else "article"
        fields["booktitle" if kind == "inproceedings" else "journal"] = esc(venue)
        if e.get("id"):
            fields["note"] = esc(str(e["id"]))
    if e.get("url"):
        fields["url"] = e["url"]
    if level != "L3":
        fields["note"] = (fields.get("note", "") + ". " if fields.get("note") else "") + \
            f"[Verification {level}: not yet read in full]"
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items())
    return f"@{kind}{{{e['key']},\n{body}\n}}\n"


def main() -> None:
    entries = {e["key"]: e for e in yaml.safe_load((ROOT / "literature/bibliography.yaml").read_text())["entries"]}
    keys = cited_keys()
    missing = [k for k in keys if k not in entries]
    if missing:
        raise SystemExit(f"cited but not in bibliography.yaml (verify first, never cite from memory): {missing}")
    text = "% Generated by manuscript/make_bib.py from literature/bibliography.yaml. Do not edit by hand.\n\n"
    text += "\n".join(entry(entries[k]) for k in keys)
    (HERE / "refs.bib").write_text(text)
    below = [k for k in keys if entries[k]["verification"] != "L3"]
    print(f"{len(keys)} entries written; {len(below)} below L3 (must be read in full before submission)")


if __name__ == "__main__":
    main()
